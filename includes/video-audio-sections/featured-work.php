// Accepts a full YouTube URL (watch / shorts / youtu.be / embed) or a bare 11-char ID.
function kd_yt_id($v)
{
  $v = trim((string) $v);
  if ($v === '') return '';
  if (preg_match('~^[A-Za-z0-9_-]{11}$~', $v)) return $v;
  if (preg_match('~(?:youtu\.be/|youtube(?:-nocookie)?\.com/(?:watch\?(?:.*&)?v=|shorts/|embed/|live/|v/))([A-Za-z0-9_-]{11})~', $v, $m)) return $m[1];
  return '';
}

// Asks YouTube whether an ID is a Short (best-effort, cached on disk).
// /shorts/ID answers 200 for Shorts and redirects to /watch for normal videos.
// Returns 'reel', 'landscape', or '' when it could not be determined.
function kd_yt_is_short($id)
{
  $file = sys_get_temp_dir() . '/kd_yt_' . $id . '.txt';
  if (is_file($file)) {
    $age = time() - (int) @filemtime($file);
    $val = trim((string) @file_get_contents($file));
    if (($val === 'reel' || $val === 'landscape') && $age < 2592000) return $val; // 30 days
    if ($val === 'unknown' && $age < 3600) return '';                              // retry after 1 h
  }

  $result = '';
  if (function_exists('curl_init')) {
    $ch = curl_init('https://www.youtube.com/shorts/' . $id);
    curl_setopt_array($ch, [
      CURLOPT_NOBODY         => true,
      CURLOPT_HEADER         => true,
      CURLOPT_FOLLOWLOCATION => false,
      CURLOPT_RETURNTRANSFER => true,
      CURLOPT_TIMEOUT        => 3,
      CURLOPT_CONNECTTIMEOUT => 2,
      CURLOPT_USERAGENT      => 'Mozilla/5.0 (compatible; KDFormatCheck/1.0)',
    ]);
    $headers = (string) curl_exec($ch);
    $code    = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);

    if ($code === 200) {
      $result = 'reel';
    } elseif ($code >= 300 && $code < 400 && preg_match('~^location:\s*\S*/watch~im', $headers)) {
      $result = 'landscape';
    }
  }
  @file_put_contents($file, $result !== '' ? $result : 'unknown');
  return $result;
}

// Early guess from a local poster image's real size (browser re-checks local videos later).
function kd_poster_format($poster)
{
  $poster = trim((string) $poster);
  if ($poster === '' || preg_match('~^https?://~i', $poster)) return '';
  $bases = [__DIR__, rtrim((string) ($_SERVER['DOCUMENT_ROOT'] ?? ''), '/')];
  foreach ($bases as $base) {
    $f = $base . '/' . ltrim($poster, '/');
    if (is_file($f) && ($size = @getimagesize($f))) {
      return $size[0] >= $size[1] ? 'landscape' : 'reel';
    }
  }
  return '';
}

// Works out whether a tile is a 'reel' or a 'landscape' video.
// Returns [format, locked]. locked = true means the browser doesn't need to double-check.
function kd_detect_format($p)
{
  $want = strtolower(trim($p['format'] ?? ''));
  if ($want === 'reel' || $want === 'landscape') return [$want, true];   // manual override

  $local = trim($p['local'] ?? '');
  $raw   = trim($p['youtube'] ?? '');

  if ($local === '' && $raw !== '') {
    if (stripos($raw, '/shorts/') !== false) return ['reel', true];
    $id = kd_yt_id($raw);
    if ($id !== '') {
      $r = kd_yt_is_short($id);
      return [$r !== '' ? $r : 'landscape', true];
    }
  }

  $byPoster = kd_poster_format($p['poster'] ?? '');
  return [$byPoster !== '' ? $byPoster : 'reel', false];
}

function kd_bg($img, $grad)
{
  $img = trim((string) $img);
  // If the image is missing the gradient simply shows underneath.
  $url = $img !== '' ? "url('" . htmlspecialchars($img, ENT_QUOTES) . "') center/cover no-repeat, " : '';
  return $url . $grad;
}

function kd_tile($p, $featured = false)
