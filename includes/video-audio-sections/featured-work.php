<script>
  (function() {
    var sec = document.getElementById('kd-work');
    if (!sec) return;

    var PREVIEW = parseFloat(sec.getAttribute('data-preview')) || 5; // hover preview length (seconds)
    var START_AT = 0.1;
    var currentTile = null; // tile whose popup is open

    /* ---------- time badge (auto duration) ---------- */
    function pad(n) {
      return (n < 10 ? '0' : '') + n;
    }

    function fmtTime(s) {
      s = Math.round(s);
      var h = Math.floor(s / 3600),
        m = Math.floor(s % 3600 / 60),
        x = s % 60;
      return (h ? h + ':' + pad(m) : pad(m)) + ':' + pad(x);
    }

    function setTime(tile, sec) {
      if (!tile || !isFinite(sec) || sec <= 0) return;
      var t = tile.querySelector('.kd-vid__time');
      if (t) t.textContent = fmtTime(sec);
    }

    /* ---------- row limit: only MAX_ROWS rows visible ---------- */
    var MAX_ROWS = parseInt(sec.getAttribute('data-rows'), 10) || 0;
    var expanded = false;
    var gridEl = document.getElementById('kd-grid');
    var toggleWrap = document.getElementById('kd-toggle-wrap');
    var toggleBtn = document.getElementById('kd-toggle');

    // Rows are measured from where the tiles actually land in the grid, so it works
    // for any mix of reels and landscape tiles at every screen size.
    function applyLimit() {
      var tiles = gridEl.querySelectorAll('.kd-vid');

      // Layout mode from what is currently visible: all landscape -> 2 per row,
      // otherwise (all reels, or a mix) the 5-column grid.
      var shownCount = 0,
        landCount = 0;
      tiles.forEach(function(t) {
        if (t.hidden) return;
        shownCount++;
        if (t.classList.contains('kd-vid--landscape')) landCount++;
      });
      gridEl.classList.toggle('kd-work__grid--land', shownCount > 0 && landCount === shownCount);

      tiles.forEach(function(t) {
        t.classList.remove('kd-vid--over');
      });
      if (!MAX_ROWS) return;

      var vis = [],
        tops = [];
      tiles.forEach(function(t) {
        if (t.hidden) return;
        vis.push(t);
        var y = t.offsetTop,
          found = false;
        for (var i = 0; i < tops.length; i++) {
          if (Math.abs(tops[i] - y) <= 2) {
            found = true;
            break;
          }
        }
        if (!found) tops.push(y);
      });
      tops.sort(function(a, b) {
        return a - b;
      });

      var cutoff = tops.length > MAX_ROWS ? tops[MAX_ROWS - 1] + 2 : Infinity;
      var over = 0;
      vis.forEach(function(t) {
        if (t.offsetTop > cutoff) {
          over++;
          if (!expanded) {
            t.classList.add('kd-vid--over');
            stopPreview(t);
          }
        }
      });
      toggleWrap.hidden = over === 0;
      toggleBtn.textContent = expanded ? 'Show less' : 'Show more projects';
    }

    toggleBtn.addEventListener('click', function() {
      expanded = !expanded;
      applyLimit();
    });

    var viewAll = sec.querySelector('.kd-work__btn');
    if (viewAll) {
      viewAll.addEventListener('click', function() {
        expanded = true;
        applyLimit();
      });
    }

    var rzTimer;
    window.addEventListener('resize', function() {
      clearTimeout(rzTimer);
      rzTimer = setTimeout(applyLimit, 150);
    });
    window.addEventListener('load', applyLimit);

    /* ---------- format detection: reel (portrait) vs landscape ---------- */
    var topEl = sec.querySelector('.kd-work__top');

    function classify(w, h) {
      return (w && h && w / h >= 1) ? 'landscape' : 'reel';
    }

    function setFormat(tile, fmt) {
      tile.classList.toggle('kd-vid--landscape', fmt === 'landscape');
      tile.classList.toggle('kd-vid--reel', fmt !== 'landscape');
      tile.setAttribute('data-format', fmt);
      if (tile.classList.contains('kd-vid--featured') && topEl) {
        topEl.classList.toggle('kd-work__top--land', fmt === 'landscape');
      }
      applyLimit();
    }

    // Local videos: read the real size AND length from the file's metadata (no full download).
    // Format is only changed on tiles that aren't locked (manual / YouTube).
    sec.querySelectorAll('.kd-vid[data-local]:not([data-local=""])').forEach(function(tile) {
      var probe = document.createElement('video');
      probe.preload = 'metadata';
      probe.muted = true;
      probe.addEventListener('loadedmetadata', function() {
        if (tile.getAttribute('data-locked') !== '1') {
          setFormat(tile, classify(probe.videoWidth, probe.videoHeight));
        }
        setTime(tile, probe.duration);
        probe.removeAttribute('src');
        probe.load();
      });
      probe.src = tile.getAttribute('data-local');
    });

    /* ---------- category filter ---------- */
    var chips = sec.querySelectorAll('.kd-chip'),
      gridTiles = sec.querySelectorAll('#kd-grid .kd-vid'),
      empty = document.getElementById('kd-empty');

    chips.forEach(function(chip) {
      chip.addEventListener('click', function() {
        var f = chip.getAttribute('data-filter'),
          shown = 0;
        chips.forEach(function(c) {
          var on = c === chip;
          c.classList.toggle('is-active', on);
          c.setAttribute('aria-pressed', on);
        });
        gridTiles.forEach(function(t) {
          var match = f === 'all' || (' ' + t.getAttribute('data-cat') + ' ').indexOf(' ' + f + ' ') > -1;
          t.hidden = !match;
          if (!match) stopPreview(t);
          if (match) shown++;
        });
        empty.hidden = shown > 0;
        applyLimit();
      });
    });

    /* ---------- YouTube embed URL (privacy domain, no branding) ---------- */
    function ytSrc(id, preview) {
      return 'https://www.youtube-nocookie.com/embed/' + id +
        '?autoplay=1&loop=1&playlist=' + id +
        '&controls=0&disablekb=1&fs=0&rel=0&modestbranding=1&iv_load_policy=3&playsinline=1' +
        '&enablejsapi=1&mute=' + (preview ? 1 : 0) +
        '&origin=' + encodeURIComponent(location.origin);
    }

    /* ---------- hover preview (muted, looping, inside the card) ---------- */
    var allTiles = sec.querySelectorAll('.kd-vid.has-video');

    function startPreview(tile) {
      if (tile.classList.contains('is-playing') || tile.__starting) return;
      var v = tile.querySelector('video.kd-vid__media');
      if (v) {
        var p = v.play();
        if (p && p.catch) p.catch(function() {});
        return;
      }
      var id = tile.getAttribute('data-yt');
      if (id && !tile.querySelector('iframe')) {
        var f = document.createElement('iframe');
        f.className = 'kd-vid__frame';
        f.tabIndex = -1;
        f.setAttribute('aria-hidden', 'true');
        f.setAttribute('allow', 'autoplay; encrypted-media');
        f.setAttribute('referrerpolicy', 'strict-origin-when-cross-origin');
        f.addEventListener('load', function() {
          ytListen(f);
          // small delay so the poster doesn't flash black while the player boots
          setTimeout(function() {
            if (tile.contains(f)) tile.classList.add('is-playing');
          }, 450);
        });
        f.src = ytSrc(id, true);
        tile.insertBefore(f, tile.firstChild);
      }
    }

    function stopPreview(tile) {
      var v = tile.querySelector('video.kd-vid__media');
      if (v) {
        v.pause();
        try {
          v.currentTime = START_AT;
        } catch (e) {}
      }
      var f = tile.querySelector('iframe');
      if (f) f.remove();
      tile.classList.remove('is-playing');
    }

    allTiles.forEach(function(tile) {
      var v = tile.querySelector('video.kd-vid__media');
      if (v) {
        v.addEventListener('playing', function() {
          tile.classList.add('is-playing');
        });
        // keep the hover preview short: loop only the first PREVIEW seconds
        v.addEventListener('timeupdate', function() {
          if (v.currentTime >= PREVIEW) v.currentTime = START_AT;
        });
      }
      tile.addEventListener('mouseenter', function() {
        startPreview(tile);
      });
      tile.addEventListener('mouseleave', function() {
        stopPreview(tile);
      });
      tile.addEventListener('focus', function() {
        startPreview(tile);
      });
      tile.addEventListener('blur', function() {
        stopPreview(tile);
      });
    });

    // Touch screens have no hover: play the tiles that are mostly on screen instead.
    if (window.matchMedia('(hover: none)').matches && 'IntersectionObserver' in window) {
      var io = new IntersectionObserver(function(entries) {
        entries.forEach(function(en) {
          if (en.isIntersecting) startPreview(en.target);
          else stopPreview(en.target);
        });
      }, {
        threshold: 0.7
      });
      allTiles.forEach(function(t) {
        io.observe(t);
      });
    }

    /* ---------- vertical lightbox (never leaves the site) ---------- */
    var modal = document.getElementById('kd-modal'),
      body = document.getElementById('kd-modal-body');

    function ytCmd(frame, func, args) {
      if (frame && frame.contentWindow) {
        frame.contentWindow.postMessage(JSON.stringify({
          event: 'command',
          func: func,
          args: args === undefined ? '' : args
        }), '*');
      }
    }

    // Ask a YouTube frame to report back its duration / current time.
    function ytListen(frame) {
      function ask() {
        if (frame && frame.contentWindow) {
          frame.contentWindow.postMessage(JSON.stringify({
            event: 'listening',
            id: 1,
            channel: 'widget'
          }), '*');
        }
      }
      ask();
      setTimeout(ask, 600);
    }

    window.addEventListener('message', function(e) {
      if (String(e.origin).indexOf('youtube') === -1) return;
      var d;
      try {
        d = JSON.parse(e.data);
      } catch (err) {
        return;
      }
      if (!d || d.event !== 'infoDelivery' || !d.info) return;

      // popup player -> just fill in the time badge
      var popFrame = body.querySelector('iframe');
      if (popFrame && popFrame.contentWindow === e.source) {
        if (d.info.duration) setTime(currentTile, d.info.duration);
        return;
      }
      // hover preview frame -> time badge + keep the preview short
      for (var i = 0; i < allTiles.length; i++) {
        var f = allTiles[i].querySelector('iframe');
        if (f && f.contentWindow === e.source) {
          if (d.info.duration) setTime(allTiles[i], d.info.duration);
          if (d.info.currentTime >= PREVIEW) ytCmd(f, 'seekTo', [0, true]);
          return;
        }
      }
    });

    function openTile(tile) {
      var local = tile.getAttribute('data-local'),
        id = tile.getAttribute('data-yt');
      if (!local && !id) return;
      stopPreview(tile);
      currentTile = tile;
      modal.classList.toggle('kd-modal--landscape', tile.getAttribute('data-format') === 'landscape');
      body.className = 'kd-modal__body';
      body.innerHTML = '';

      if (local) {
        var v = document.createElement('video');
        v.src = local;
        v.controls = true;
        v.autoplay = true;
        v.loop = true;
        v.setAttribute('playsinline', '');
        body.appendChild(v);
      } else {
        var f = document.createElement('iframe');
        f.className = 'kd-vid__frame';
        f.setAttribute('allow', 'autoplay; encrypted-media');
        f.setAttribute('referrerpolicy', 'strict-origin-when-cross-origin');
        f.setAttribute('title', 'Video player');
        f.addEventListener('load', function() {
          ytListen(f);
        });
        f.src = ytSrc(id, false);
        var tap = document.createElement('button');
        tap.type = 'button';
        tap.className = 'kd-modal__tap';
        tap.setAttribute('aria-label', 'Play or pause');
        var paused = false;
        tap.addEventListener('click', function() {
          paused = !paused;
          ytCmd(f, paused ? 'pauseVideo' : 'playVideo');
          body.classList.toggle('is-paused', paused);
        });
        body.appendChild(f);
        body.appendChild(tap);
      }
      modal.showModal();
    }

    function closeModal() {
      body.innerHTML = '';
      if (modal.open) modal.close();
    }

    allTiles.forEach(function(tile) {
      tile.addEventListener('click', function() {
        openTile(tile);
      });
      tile.addEventListener('keydown', function(e) {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault();
          openTile(tile);
        }
      });
    });

    modal.querySelector('.kd-modal__close').addEventListener('click', closeModal);
    modal.addEventListener('click', function(e) {
      if (e.target === modal) closeModal();
    });
    modal.addEventListener('close', function() {
      body.innerHTML = '';
    });

    applyLimit();
  })();
</script>