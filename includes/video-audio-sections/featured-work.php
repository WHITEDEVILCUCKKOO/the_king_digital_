    // hqdefault has side bars for Shorts (cropped away by "cover"); mqdefault is a clean 16:9
    $poster = 'https://i.ytimg.com/vi/' . $yt . '/' . ($fmt === 'reel' ? 'hqdefault' : 'mqdefault') . '.jpg';
  }
  $has    = ($local !== '' || $yt !== '');
  $useFrame = ($local !== '' && $poster === '');   // no cover image -> use a frame of the video itself
  $cls    = 'kd-vid kd-vid--' . $fmt . ($featured ? ' kd-vid--featured' : '') . ($has ? ' has-video' : '') . ($useFrame ? ' kd-vid--frame' : '');
  $attrs  = $featured ? '' : ' data-cat="' . htmlspecialchars($p['cat']) . '"';
  $title  = htmlspecialchars($p['title']);
?>
  <article class="<?= $cls ?>" <?= $attrs ?>
    style="background: <?= kd_bg($poster, $p['grad']) ?>"
    data-local="<?= htmlspecialchars($local, ENT_QUOTES) ?>"
    data-yt="<?= htmlspecialchars($yt, ENT_QUOTES) ?>"
    data-format="<?= $fmt ?>" <?= $locked ? ' data-locked="1"' : '' ?>
    <?= $has ? 'tabindex="0" role="button" aria-label="Play ' . $title . '"' : '' ?>>
    <?php if ($local !== ''): ?>
      <video class="kd-vid__media" src="<?= htmlspecialchars($local, ENT_QUOTES) ?><?= $useFrame ? '#t=0.1' : '' ?>" muted loop playsinline preload="<?= $useFrame ? 'metadata' : 'none' ?>" tabindex="-1"></video>
    <?php endif; ?>
    <span class="kd-vid__tag"><?= htmlspecialchars($p['tag']) ?></span>
    <span class="kd-vid__play" aria-hidden="true"><svg viewBox="0 0 24 24">
        <path d="M7 4l13 8-13 8z" />
      </svg></span>
    <div class="kd-vid__info">
      <div>
        <div class="kd-vid__title"><?= $title ?></div>
        <div class="kd-vid__sub"><?= htmlspecialchars($p['sub']) ?></div>
      </div>
      <span class="kd-vid__time"><?= htmlspecialchars($p['time'] ?? '') ?></span>
    </div>
  </article>
<?php
}
