<script>

(function(){

  const faqSections =
    document.querySelectorAll('.kd-faq-clean');

  if(!faqSections.length) return;


  faqSections.forEach(function(section){

    const items =
      section.querySelectorAll('.kd-faq-clean-item');


    items.forEach(function(item){

      const button =
        item.querySelector('.kd-faq-clean-question');

      if(!button) return;


      button.addEventListener('click',function(){

        const isOpen =
          item.classList.contains('is-open');


        items.forEach(function(otherItem){

          otherItem.classList.remove('is-open');

          const otherButton =
            otherItem.querySelector('.kd-faq-clean-question');

          if(otherButton){

            otherButton.setAttribute(
              'aria-expanded',
              'false'
            );

          }

        });


        if(!isOpen){

          item.classList.add('is-open');

          button.setAttribute(
            'aria-expanded',
            'true'
          );

        }else{

          button.setAttribute(
            'aria-expanded',
            'false'
          );

        }

      });

    });

  });

})();

</script>