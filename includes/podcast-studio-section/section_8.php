<script>

(function(){

    const faqSection =
        document.querySelector(
            '.kd-pod-faq-pro'
        );

    if(!faqSection){
        return;
    }


    const faqItems =
        faqSection.querySelectorAll(
            '.kd-pfaq-item'
        );


    function closeItem(item){

        const question =
            item.querySelector(
                '.kd-pfaq-question'
            );

        const answer =
            item.querySelector(
                '.kd-pfaq-answer'
            );


        item.classList.remove(
            'active'
        );


        question.setAttribute(
            'aria-expanded',
            'false'
        );


        answer.style.maxHeight =
            '0px';
    }


    function openItem(item){

        const question =
            item.querySelector(
                '.kd-pfaq-question'
            );

        const answer =
            item.querySelector(
                '.kd-pfaq-answer'
            );


        item.classList.add(
            'active'
        );


        question.setAttribute(
            'aria-expanded',
            'true'
        );


        answer.style.maxHeight =
            answer.scrollHeight +
            'px';
    }


    faqItems.forEach(
        function(item){

            const button =
                item.querySelector(
                    '.kd-pfaq-question'
                );


            button.addEventListener(
                'click',
                function(){

                    const alreadyOpen =
                        item.classList.contains(
                            'active'
                        );


                    /* CLOSE ALL */

                    faqItems.forEach(
                        function(otherItem){

                            closeItem(
                                otherItem
                            );

                        }
                    );


                    /* OPEN CURRENT ONLY IF CLOSED */

                    if(!alreadyOpen){

                        openItem(
                            item
                        );

                    }

                }
            );

        }
    );


    /* FIRST FAQ OPEN DEFAULT */

    if(faqItems.length){

        faqItems.forEach(
            function(item){

                closeItem(
                    item
                );

            }
        );


        openItem(
            faqItems[0]
        );

    }


    /* RECALCULATE OPEN HEIGHT ON RESIZE */

    window.addEventListener(
        'resize',
        function(){

            const activeItem =
                faqSection.querySelector(
                    '.kd-pfaq-item.active'
                );


            if(activeItem){

                const answer =
                    activeItem.querySelector(
                        '.kd-pfaq-answer'
                    );


                answer.style.maxHeight =
                    answer.scrollHeight +
                    'px';

            }

        }
    );

})();

</script>