<script>

(function(){

    const section =
        document.querySelector(
            '.kd-podcast-audience-new'
        );

    if(!section){
        return;
    }


    const tracks =
        section.querySelectorAll(
            '.kd-pan-track'
        );


    /*
    Duplicate every row automatically
    so the marquee loops continuously.
    */

    tracks.forEach(function(track){

        if(
            track.dataset.cloned === 'yes'
        ){
            return;
        }


        const original =
            Array.from(
                track.children
            );


        original.forEach(
            function(card){

                const clone =
                    card.cloneNode(true);

                clone.setAttribute(
                    'aria-hidden',
                    'true'
                );

                track.appendChild(
                    clone
                );

            }
        );


        track.dataset.cloned =
            'yes';

    });

})();

</script>


