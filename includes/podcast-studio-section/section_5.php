<script>
    (function() {

        const section =
            document.querySelector('.kd-pmf-final');

        if (!section) {
            return;
        }

        const tabs =
            section.querySelectorAll('.kd-pmf-final-tab');

        const panels =
            section.querySelectorAll('.kd-pmf-final-panel');


        tabs.forEach(function(tab) {

            tab.addEventListener('click', function() {

                const target =
                    tab.getAttribute('data-kd-tab');


                /* PAUSE ALL VIDEOS */

                section
                    .querySelectorAll('video')
                    .forEach(function(video) {
                        video.pause();
                    });


                /* RESET TABS */

                tabs.forEach(function(button) {
                    button.classList.remove('active');
                });


                /* RESET PANELS */

                panels.forEach(function(panel) {
                    panel.classList.remove('active');
                });


                /* ACTIVE TAB */

                tab.classList.add('active');


                /* ACTIVE PANEL */

                const activePanel =
                    section.querySelector(
                        '[data-kd-panel="' + target + '"]'
                    );

                if (activePanel) {
                    activePanel.classList.add('active');
                }

            });

        });

    })();
</script>

