<script>


(function () {

  function initOtpFaq() {

    const faqSection = document.getElementById("kdOtpFaqSection");

    if (!faqSection) return;

    const faqItems = faqSection.querySelectorAll(".kd-otp-faq-item");

    faqItems.forEach(function (item) {

      const button = item.querySelector(".kd-otp-faq-question");

      if (!button) return;

      button.addEventListener("click", function () {

        const isCurrentlyOpen =
          item.classList.contains("kd-otp-active");


        /* CLOSE ALL OTHER FAQ ITEMS */

        faqItems.forEach(function (otherItem) {

          if (otherItem !== item) {

            otherItem.classList.remove("kd-otp-active");

            const otherButton =
              otherItem.querySelector(".kd-otp-faq-question");

            if (otherButton) {
              otherButton.setAttribute(
                "aria-expanded",
                "false"
              );
            }

          }

        });


        /* TOGGLE CLICKED FAQ */

        if (isCurrentlyOpen) {

          item.classList.remove("kd-otp-active");

          button.setAttribute(
            "aria-expanded",
            "false"
          );

        } else {

          item.classList.add("kd-otp-active");

          button.setAttribute(
            "aria-expanded",
            "true"
          );

        }

      });

    });

  }


  /* WORKS EVEN IF CODE IS ADDED LATE */

  if (document.readyState === "loading") {

    document.addEventListener(
      "DOMContentLoaded",
      initOtpFaq
    );

  } else {

    initOtpFaq();

  }

})();
</script>