<script>

(function(){

    const faqItems =
        document.querySelectorAll(
            ".kdfaq-item"
        );


    function closeFaq(item){

        item.classList.remove(
            "active"
        );

        const answer =
            item.querySelector(
                ".kdfaq-answer"
            );

        if(answer){

            answer.style.maxHeight =
                null;

        }

    }


    function openFaq(item){

        item.classList.add(
            "active"
        );

        const answer =
            item.querySelector(
                ".kdfaq-answer"
            );

        if(answer){

            answer.style.maxHeight =
                answer.scrollHeight
                +
                "px";

        }

    }


    faqItems.forEach(
        function(item){

            const button =
                item.querySelector(
                    ".kdfaq-question"
                );


            if(!button){
                return;
            }


            button.addEventListener(
                "click",
                function(){

                    const wasOpen =
                        item.classList.contains(
                            "active"
                        );


                    faqItems.forEach(
                        function(otherItem){

                            closeFaq(
                                otherItem
                            );

                        }
                    );


                    if(!wasOpen){

                        openFaq(
                            item
                        );

                    }

                }
            );

        }
    );


    /* FIRST FAQ OPEN DEFAULT */

    const firstItem =
        document.querySelector(
            ".kdfaq-item.active"
        );


    if(firstItem){

        requestAnimationFrame(
            function(){

                openFaq(
                    firstItem
                );

            }
        );

    }


    /* UPDATE HEIGHT AFTER RESIZE */

    window.addEventListener(
        "resize",
        function(){

            const activeItem =
                document.querySelector(
                    ".kdfaq-item.active"
                );


            if(activeItem){

                const answer =
                    activeItem.querySelector(
                        ".kdfaq-answer"
                    );


                if(answer){

                    answer.style.maxHeight =
                        answer.scrollHeight
                        +
                        "px";

                }

            }

        }
    );

})();

</script>